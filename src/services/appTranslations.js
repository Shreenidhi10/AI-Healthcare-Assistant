/**
 * Translates a given English string into the selected language code.
 * Falls back to English if no translation is found.
 */
export function getTranslatedText(text, langCode) {
  if (!text || !langCode || langCode === "eng_Latn") {
    return text;
  }

  // Check language code directly or shortened code (e.g. hin_Deva -> hi)
  const langDict = UI_TRANSLATIONS[langCode];
  if (langDict && langDict[text]) {
    return langDict[text];
  }

  return text;
}
